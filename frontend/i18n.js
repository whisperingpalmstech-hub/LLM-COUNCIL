let currentLang = "en";

export function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    
    // Update all static elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (translations[currentLang][key]) {
        // If it contains lucide icons, we need to preserve them.
        // It's safer to just set textContent if there are no child elements.
        // But some elements have innerHTML like <i data-lucide="..."></i> text
        const icon = el.querySelector("i[data-lucide]");
        if (icon) {
          // Re-create the content with the icon and the translated text
          el.innerHTML = icon.outerHTML + " " + translations[currentLang][key];
        } else {
          el.textContent = translations[currentLang][key];
        }
      }
    });

    return true;
  }
  return false;
}

export function t(key) {
  return translations[currentLang][key] || key;
}

export function getCurrentLang() {
  return currentLang;
}
